/**
 * Jira REST API service — create Epics and sub-tasks for remediation actions.
 *
 * Requires Jira Cloud credentials in .env.local:
 *   JIRA_BASE_URL=https://yourcompany.atlassian.net
 *   JIRA_EMAIL=your-atlassian-email@example.com
 *   JIRA_API_TOKEN=  (from https://id.atlassian.com/manage-profile/security/api-tokens)
 *   JIRA_PROJECT_KEY=ERA
 *
 * When credentials are absent the service logs and returns a mock result — it
 * never throws so the delivery pipeline degrades gracefully.
 */

import { appEnv, hasJiraConfig } from '@/lib/env';

// ─── Types ────────────────────────────────────────────────────────────────────

export interface JiraTaskInput {
  title: string;
  ownerRole: string;
  priority: string;
  dueLabel: string;
  instructions: string;
}

export interface JiraEpicInput {
  engagementName: string;
  clientName: string;
  leadConsultant: string;
  readinessDecision: string;
  readinessScore: number;
  epicSummary: string;            // one-line description for the Epic issue
  epicDescription: string;        // full Jira description (ADF text or markdown)
  tasks: JiraTaskInput[];
}

export interface JiraCreatedIssue {
  id: string;
  key: string;
  url: string;
}

export interface JiraEpicResult {
  live: boolean;                  // true = real Jira API was called
  epic?: JiraCreatedIssue;
  subTasks: JiraCreatedIssue[];
  error?: string;
}

// ─── Auth helper ──────────────────────────────────────────────────────────────

function buildBasicAuth(): string {
  const email = appEnv.jiraEmail ?? '';
  const token = appEnv.jiraApiToken ?? '';
  return `Basic ${Buffer.from(`${email}:${token}`).toString('base64')}`;
}

// ─── Priority mapping ─────────────────────────────────────────────────────────

function toJiraPriority(p: string): string {
  const map: Record<string, string> = {
    critical: 'Highest',
    high: 'High',
    medium: 'Medium',
    low: 'Low',
  };
  return map[p.toLowerCase()] ?? 'Medium';
}

// ─── Create a single Jira issue ───────────────────────────────────────────────

async function createIssue(payload: Record<string, unknown>): Promise<JiraCreatedIssue> {
  const url = `${appEnv.jiraBaseUrl}/rest/api/3/issue`;

  const res = await fetch(url, {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      'Authorization': buildBasicAuth(),
      'Accept': 'application/json',
    },
    body: JSON.stringify(payload),
    signal: AbortSignal.timeout(15_000),
  });

  const text = await res.text().catch(() => '');

  if (!res.ok) {
    throw new Error(`Jira API ${res.status}: ${text.slice(0, 400)}`);
  }

  const data = JSON.parse(text) as { id: string; key: string; self: string };
  const baseUrl = appEnv.jiraBaseUrl ?? '';
  return {
    id: data.id,
    key: data.key,
    url: `${baseUrl}/browse/${data.key}`,
  };
}

// ─── Build Atlassian Document Format body ────────────────────────────────────

function adfParagraph(text: string): Record<string, unknown> {
  return {
    type: 'paragraph',
    content: [{ type: 'text', text }],
  };
}

function buildEpicDescription(input: JiraEpicInput): Record<string, unknown> {
  const lines: Record<string, unknown>[] = [
    adfParagraph(`Engagement: ${input.engagementName}`),
    adfParagraph(`Client: ${input.clientName}`),
    adfParagraph(`Lead Consultant: ${input.leadConsultant}`),
    adfParagraph(`Readiness: ${input.readinessDecision} · ${input.readinessScore}%`),
    adfParagraph(''),
    adfParagraph(input.epicDescription),
    adfParagraph(''),
    adfParagraph(`Generated by Engagement Ready AI · IBM Consulting`),
  ];
  return { type: 'doc', version: 1, content: lines };
}

function buildTaskDescription(task: JiraTaskInput): Record<string, unknown> {
  return {
    type: 'doc',
    version: 1,
    content: [
      adfParagraph(`Role: ${task.ownerRole}`),
      adfParagraph(`Priority: ${task.priority}`),
      adfParagraph(`Due: ${task.dueLabel}`),
      adfParagraph(''),
      adfParagraph(task.instructions),
    ],
  };
}

// ─── Public API ───────────────────────────────────────────────────────────────

/**
 * Create a Jira Epic for the remediation plan, then create one Story per task.
 * Returns a mock result (live=false) when Jira credentials are absent.
 */
export async function createJiraEpic(input: JiraEpicInput): Promise<JiraEpicResult> {
  if (!hasJiraConfig()) {
    console.log('[jira] Credentials not configured — returning mock Jira result.');
    return buildMockJiraResult(input);
  }

  const projectKey = appEnv.jiraProjectKey ?? 'ERA';
  console.log(`[jira] Creating Epic in project ${projectKey} for "${input.engagementName}"`);

  let epic: JiraCreatedIssue;
  try {
    epic = await createIssue({
      fields: {
        project: { key: projectKey },
        summary: input.epicSummary,
        description: buildEpicDescription(input),
        issuetype: { name: 'Epic' },
        priority: { name: 'High' },
      },
    });
    console.log(`[jira] ✓ Epic created: ${epic.key} → ${epic.url}`);
  } catch (err) {
    const error = err instanceof Error ? err.message : String(err);
    console.warn('[jira] Epic creation failed:', error);
    return { live: true, subTasks: [], error };
  }

  // Create one Story per task, linked to the Epic
  const subTasks: JiraCreatedIssue[] = [];
  for (const task of input.tasks) {
    try {
      const story = await createIssue({
        fields: {
          project: { key: projectKey },
          summary: task.title,
          description: buildTaskDescription(task),
          issuetype: { name: 'Story' },
          priority: { name: toJiraPriority(task.priority) },
          // Link to epic — Jira Cloud uses "Epic Link" or "Parent"
          // Try both: next-gen projects use parent, classic use customfield
          parent: { key: epic.key },
        },
      });
      subTasks.push(story);
      console.log(`[jira] ✓ Story: ${story.key} — ${task.title}`);
    } catch (err) {
      console.warn(`[jira] Story failed for "${task.title}":`, err instanceof Error ? err.message : err);
    }
  }

  return { live: true, epic, subTasks };
}

// ─── Mock fallback ────────────────────────────────────────────────────────────

function buildMockJiraResult(input: JiraEpicInput): JiraEpicResult {
  const projectKey = appEnv.jiraProjectKey ?? 'ERA';
  const epic: JiraCreatedIssue = {
    id: 'mock-epic-001',
    key: `${projectKey}-1`,
    url: `https://your-domain.atlassian.net/browse/${projectKey}-1`,
  };
  const subTasks: JiraCreatedIssue[] = input.tasks.map((t, i) => ({
    id: `mock-task-${i + 2}`,
    key: `${projectKey}-${i + 2}`,
    url: `https://your-domain.atlassian.net/browse/${projectKey}-${i + 2}`,
  }));
  return { live: false, epic, subTasks };
}
